#!/usr/bin/env python3
"""weekly.py — a week-ahead brief across every registered familiar project. Read-only on projects.

    python scripts/weekly.py                 # write _overview/weekly-<today>.md and weekly-latest.{md,json,html}
    python scripts/weekly.py --scheduled     # same, if weekly_enabled; used by the scheduler entry
    python scripts/weekly.py --catch-up      # same, only if enabled and no weekly brief in the last 6 days

The week is the coming Monday to Friday when run on a Friday, Saturday or Sunday, and today through the
next 7 days when run Monday to Thursday. It collects through `fleet_overview.py` and `brief.py` (same
registry, same per-project scripts, same fallbacks) and renders what is due each day, a cautions list
(overdue carry-overs, at-risk or not-started items, same-day collisions, heavy weeks, meeting clashes,
time off, tentative dates, stale projects), the open tasks of every project with a date in the week, and
the first dates after it. Every caution is computed from what the projects wrote; nothing is inferred.
Settings (`weekly_enabled`, `weekly_retention_weeks`, `weekly_top_tasks`) live in `brief-settings.md`.
The day and time it runs are set only in the scheduler entry (`schedule.py enable --brief weekly`).
Standard library only.
"""

# familiar's floor is Python 3.10. On anything older, stop with a plain message instead of a traceback.
import sys
if sys.version_info < (3, 10):
    sys.exit("familiar needs Python 3.10 or newer, but this is Python %d.%d (%s). Install Python 3.10+ "
             "(.familiar/scripts/doctor.py says how), then run this again with it." % (*sys.version_info[:2], sys.executable))

import argparse
import json
import re
import sys
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import brief as bf  # noqa: E402
import fleet_overview as fo  # noqa: E402

DEFAULTS = {"weekly_enabled": False, "weekly_retention_weeks": 8, "weekly_top_tasks": 5}
SETTING = re.compile(r"^\s*[-*]?\s*`?(weekly_enabled|weekly_retention_weeks|weekly_top_tasks)`?\s*:\s*`?([^`\s]+)`?\s*$")
STAMP = "<!-- weekly: {today} {result}; window {start} to {end}; generated by scripts/weekly.py; do not edit. Sources: {sources} -->"
STAMP_RE = re.compile(r"<!-- weekly: (\d{4}-\d{2}-\d{2}) (ok|failed);")
DATED = re.compile(r"^weekly-(\d{4}-\d{2}-\d{2})\.md$")
TEMPLATE = Path(__file__).resolve().parent / "weekly-template.html"
DATA_SLOT = "__WEEKLY_DATA__"
SCHEMA = 1  # bump when weekly-latest.json changes shape; the template checks it
CATCH_UP_DAYS = 6  # --catch-up skips when a successful weekly brief is this recent
AFTER_DAYS = 7  # "just after the week" looks this far past the window
NOT_STARTED = re.compile(r"\bnot started\b", re.IGNORECASE)
TENTATIVE = re.compile(r"\btentative\b", re.IGNORECASE)
DOW = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]


# ---------------------------------------------------------------- settings and window

def read_settings(path: Path) -> tuple[dict, list[str]]:
    settings, notes, seen = dict(DEFAULTS), [], set()
    if not path.is_file():
        return settings, [f"`{path.name}` not found; using defaults."]
    for line in fo.read(path).splitlines():
        m = SETTING.match(line)
        if not m or m.group(1) in seen:
            continue
        key, raw = m.group(1), m.group(2).strip().lower()
        seen.add(key)
        if key == "weekly_enabled":
            if raw in ("yes", "true", "on"):
                settings[key] = True
            elif raw not in ("no", "false", "off"):
                notes.append(f"`{key}: {raw}` is not yes or no; treated as no.")
            continue
        try:
            value = int(raw)
            if value < 1:
                raise ValueError
        except ValueError:
            notes.append(f"`{key}: {raw}` is not a positive whole number; using {DEFAULTS[key]}.")
            continue
        settings[key] = value
    return settings, notes


def week_window(today: str) -> tuple[str, str]:
    """(start, end): the coming Mon-Fri when `today` is Fri/Sat/Sun, else today through the next 7 days."""
    d = date.fromisoformat(today)
    if d.weekday() >= 4:
        start = d + timedelta(days=7 - d.weekday())
        return start.isoformat(), (start + timedelta(days=4)).isoformat()
    return today, (d + timedelta(days=7)).isoformat()


def day_label(iso: str) -> str:
    d = date.fromisoformat(iso)
    return f"{DOW[d.weekday()]} {iso[5:]}"


# ---------------------------------------------------------------- facts

def mine(owner: str, me: list[str]) -> bool:
    return bool(owner) and any(n.lower() in owner.lower() for n in me)


def collect(projects: list[dict], today: str, start: str, end: str, time_off: list[dict], types: dict) -> dict:
    """The week's facts, from active projects only: milestones in the window, those left open before it, those
    in the AFTER_DAYS after it, and a count of dates in parked projects (not listed)."""
    after_end = (date.fromisoformat(end) + timedelta(days=AFTER_DAYS)).isoformat()
    week, carried, after, parked = [], [], [], 0
    for due, kind, p, m in fo.dated_rows(projects):
        if p["lifecycle"] != "active":
            if kind == "overdue" or due <= after_end:
                parked += 1
            continue
        window = "overdue" if kind == "overdue" else "soon"
        fact = bf.milestone_fact(due, kind, p, m, window, today, time_off, types)
        fact["confirmed"] = m.get("confirmed") or ""
        if kind == "overdue" or due < start:
            carried.append(fact)
        elif due <= end:
            week.append(fact)
        elif due <= after_end:
            after.append(fact)
    return {"week": week, "carried": carried, "after": after, "parked": parked, "after_end": after_end}


def cautions(projects: list[dict], facts: dict, meetings: list[dict], clashes: list[str], start: str, end: str,
             today: str, time_off: list[dict], agenda_kinds: tuple = ()) -> list[dict]:
    """Every caution the data supports, high before watch, then by date. Each carries the projects it touches so
    a reader can find it again in the per-project detail. `agenda_kinds` (from `brief-settings.md`) adds one
    line counting this window's meetings of those kinds with no agenda."""
    out = []

    def add(level, kind, day, names, text):
        out.append({"level": level, "kind": kind, "date": day, "projects": sorted(set(names)), "text": text})

    for m in facts["carried"]:
        late = f"{-m['days']} day(s) overdue" if m["days"] < 0 else "dated before the week starts"
        add("high", "overdue", m["due"], [m["project"]],
            f"{m['project']}: {m['name']} was due {m['due']} ({late}); status {m['status'] or 'not set'}.")
    by_day: dict = {}
    for m in facts["week"]:
        by_day.setdefault(m["due"], []).append(m)
        where = f"{m['project']}: {m['name']} ({day_label(m['due'])})"
        if m["at_risk"]:
            add("high", "at-risk", m["due"], [m["project"]],
                f"{where} is marked at risk — " + (m["risk_reason"] or "the project's timeline records no reason."))
        elif NOT_STARTED.search(m["status"]) and m["days"] <= 3:
            add("high", "not-started", m["due"], [m["project"]], f"{where} is due in {m['days']} day(s) and still 'not started'.")
        if m["confirmed"] and TENTATIVE.search(m["confirmed"]) and m["shape"] == "deliverable":
            add("watch", "tentative", m["due"], [m["project"]], f"{where} is a deliverable with a tentative date.")
        if date.fromisoformat(m["due"]).weekday() >= 5:
            add("watch", "weekend", m["due"], [m["project"]], f"{where} falls on a weekend; plan for the Friday before.")
        if m["time_off"]:
            add("high", "time-off", m["due"], [m["project"]], f"{where} falls in your time off ({m['time_off']}).")
    for d, rows in sorted(by_day.items()):
        names = [r["project"] for r in rows]
        deliverables = [r for r in rows if r["shape"] == "deliverable"]
        if len(set(r["project"] for r in deliverables)) >= 2:
            add("high", "collision", d, names, f"{day_label(d)}: deliverables from {len(set(r['project'] for r in deliverables))} "
                f"projects land the same day — " + "; ".join(f"{r['project']}: {r['name']}" for r in deliverables) + ".")
        elif len(set(names)) >= 2:
            add("watch", "collision", d, names, f"{day_label(d)}: dates from {', '.join(sorted(set(names)))} fall on the same day.")
    deliverables = [m for m in facts["week"] if m["shape"] == "deliverable"]
    if len(deliverables) >= bf.HEAVY_WEEK:
        add("watch", "heavy-week", start, [m["project"] for m in deliverables],
            f"{len(deliverables)} deliverables fall in this window across {len(set(m['project'] for m in deliverables))} project(s).")
    for c in clashes:
        if start <= c[:10] <= end:
            add("high", "meeting-clash", c[:10], [], c)
    due_days = {m["due"]: m for m in facts["week"] if m["shape"] == "deliverable"}
    for mt in meetings:
        if mt["parked"] or not start <= mt["date"] <= end:
            continue
        if mt["time_off"]:
            add("watch", "meeting-time-off", mt["date"], [mt["project"]],
                f"{mt['project']}: {mt['meeting']} {day_label(mt['date'])} {mt['start']} falls in your time off ({mt['time_off']}).")
        if mt["kind"] == "client" and mt["date"] in due_days and due_days[mt["date"]]["project"] != mt["project"]:
            d = due_days[mt["date"]]
            add("watch", "meeting-vs-deadline", mt["date"], [mt["project"], d["project"]],
                f"{day_label(mt['date'])}: client meeting {mt['project']} {mt['meeting']} ({mt['start']}) on the day {d['project']} "
                f"has a deliverable due ({d['name']}).")
    unset = [mt for mt in meetings if not mt["parked"] and start <= mt["date"] <= end and mt["kind"] in agenda_kinds
             and mt.get("agenda_status") == "not set"]
    if unset:
        add("watch", "agendas-not-set", start, [mt["project"] for mt in unset],
            f"Agendas not set: {len(unset)} meeting(s) this week — "
            + "; ".join(f"{mt['project']}: {mt['meeting']} {day_label(mt['date'])}" for mt in unset) + ".")
    for t in time_off:
        if t["end"] < start or t["start"] > end:
            continue
        back =(date.fromisoformat(t["end"]) + timedelta(days=1))
        while back.weekday() >= 5:
            back += timedelta(days=1)
        first_back = [m for m in facts["week"] + facts["after"] if m["due"] == back.isoformat() and m["shape"] == "deliverable"]
        add("watch", "time-off", t["start"], [m["project"] for m in first_back],
            f"Time off {bf.span(t)} sits in this window" +
            (f"; first day back ({day_label(back.isoformat())}): " + "; ".join(f"{m['project']}: {m['name']}" for m in first_back)
             if first_back else "."))
    stale = {p["name"]: p for p in projects if p.get("stale")}
    for name in sorted({m["project"] for m in facts["week"] + facts["carried"]} & set(stale)):
        add("watch", "stale", start, [name], f"{name}: {fo.stale_text(stale[name])}; its dates may have moved.")
    rank = {"high": 0, "watch": 1}
    return sorted(out, key=lambda c: (rank[c["level"]], c["date"], c["kind"], c["text"]))


def project_details(projects: list[dict], facts: dict, meetings: list[dict], start: str, end: str, top: int,
                    me: list[str]) -> list[dict]:
    """One entry per active project with a milestone or meeting in the window (or open before it): the
    milestones and meetings, its status line, and its open tasks (startable first, mine marked)."""
    out = []
    for p in projects:
        if p.get("state") != "ok" or p["lifecycle"] != "active":
            continue
        ms = [m for m in facts["carried"] + facts["week"] if m["project"] == p["name"]]
        mts = [mt for mt in meetings if mt["project"] == p["name"] and start <= mt["date"] <= end]
        if not ms and not mts:
            continue
        startable, blocked = p.get("frontier", []), p.get("blocked", [])
        ranked = sorted(startable, key=lambda t: (not mine(t.get("owner", ""), me), t.get("id") or ""))
        out.append({"name": p["name"], "label": fo.label(p), "status": p.get("status") or "", "stale_text": fo.stale_text(p) if p.get("stale") else "",
                    "milestones": ms, "meetings": mts, "tasks_read": "frontier" in p,
                    "startable": [dict(t, mine=mine(t.get("owner", ""), me)) for t in ranked[:top]],
                    "startable_total": len(startable),
                    "blocked": [dict(t, mine=mine(t.get("owner", ""), me)) for t in blocked[:top]], "blocked_total": len(blocked),
                    "problems": bf.problems(p)})
    return sorted(out, key=lambda e: (min([m["due"] for m in e["milestones"]] or ["9999"]), e["name"]))


def day_rows(facts: dict, meetings: list[dict], start: str, end: str, time_off: list[dict]) -> list[dict]:
    """Every workday in the window, plus a weekend day only when something falls on it."""
    days = []
    d, last = date.fromisoformat(start), date.fromisoformat(end)
    while d <= last:
        iso = d.isoformat()
        ms = [m for m in facts["week"] if m["due"] == iso]
        mts = [mt for mt in meetings if mt["date"] == iso and not mt["parked"]]
        if d.weekday() < 5 or ms or mts:
            away = bf.off_on(time_off, iso)
            days.append({"date": iso, "label": day_label(iso), "workday": d.weekday() < 5,
                         "time_off": bf.span(away) if away else "", "milestones": ms, "meetings": mts})
        d += timedelta(days=1)
    return days


# ---------------------------------------------------------------- rendering

def owner_text(o: str, me: list[str]) -> str:
    return f" — {o}{' (you)' if mine(o, me) else ''}" if o else ""


def render(facts: dict, today: str, start: str, end: str, notes: list[str], scope: str, projects: list[dict],
           cs: list[dict], days: list[dict], details: list[dict], me: list[str], time_off: list[dict]) -> str:
    high = [c for c in cs if c["level"] == "high"]
    out = [STAMP.format(today=today, result="ok", start=start, end=end, sources=bf.sources(projects)),
           f"# Week ahead — {day_label(start)} to {day_label(end)}", "",
           f"Generated {today}. {len(facts['week'])} dated item(s) in the window, {len(facts['carried'])} open from before it, "
           f"{len(high)} caution(s) needing attention, {len(cs) - len(high)} to watch.", "",
           *([scope, ""] if scope else [])]
    if notes:
        out += ["Settings: " + " ".join(notes), ""]
    out += ["## Cautions", ""]
    if not cs:
        out.append("None.")
    for level, title in (("high", "Needs attention"), ("watch", "Watch")):
        rows = [c for c in cs if c["level"] == level]
        if rows:
            out += [f"**{title}**", ""] + [f"- {c['text']}" for c in rows] + [""]
    out += ["## Day by day", ""]
    for d in days:
        out.append(f"**{d['label']}**" + (f" — you are off ({d['time_off']})" if d["time_off"] else ""))
        lines = [f"- {m['project']} — {m['name']} ({m['type'] or 'milestone'}; {m['status'] or 'status not set'}"
                 f"{'; AT RISK' if m['at_risk'] else ''}){owner_text(m['owner'], me)}" for m in d["milestones"]]
        lines += [f"- {mt['start']}{('-' + mt['end']) if mt['end'] else ''} meeting — {mt['project']} — {mt['meeting']} ({mt['kind']})"
                  for mt in d["meetings"]]
        out += (lines or ["- Nothing dated."]) + [""]
    out += ["## What needs doing, by project", "",
            "Open tasks per project with a date this week. Task trackers do not link tasks to milestones, so these are the "
            "project's whole open list, yours first.", ""]
    for e in details:
        out.append(f"### {e['name']} ({e['label']})")
        if e["stale_text"]:
            out.append(f"_{e['stale_text']}; dates may have moved._")
        if e["status"]:
            out.append(f"Status: {e['status']}")
        out += [f"- {m['due']} — {m['name']} — {m['status'] or 'status not set'}{owner_text(m['owner'], me)}"
                + (f" — AT RISK: {m['risk_reason']}" if m["at_risk"] and m["risk_reason"] else "") +
                (" — OVERDUE" if m["days"] < 0 else "") for m in e["milestones"]]
        out += [f"- {mt['date']} {mt['start']} meeting — {mt['meeting']}" for mt in e["meetings"]]
        if not e["tasks_read"]:
            out.append("- Tasks: not read.")
        else:
            out.append(f"- Tasks: {e['startable_total']} startable, {e['blocked_total']} blocked.")
            for t in e["startable"]:
                out.append(f"  - {t['id'] + ' ' if t.get('id') else ''}{t['title']}"
                           + (f" — {t['owner']}" if t.get("owner") else ""))
            if e["startable_total"] > len(e["startable"]):
                out.append(f"  - …and {e['startable_total'] - len(e['startable'])} more startable")
            for t in e["blocked"]:
                out.append(f"  - blocked: {t['id'] + ' ' if t.get('id') else ''}{t['title']}"
                           + (f" (waiting on {', '.join(t['blocked_by'])})" if t.get("blocked_by") else ""))
        if e["problems"]:
            out.append("- Data problems: " + "; ".join(e["problems"]))
        out.append("")
    if not details:
        out += ["None.", ""]
    out += [f"## Just after the week, to {facts['after_end']}", "", "Dates just past the window, so Monday-after preparation is not a surprise.", ""]
    out += [f"- {m['due']} — **{m['project']}** — {m['name']} — {m['status'] or 'status not set'}"
            + (" — AT RISK" if m["at_risk"] else "") + owner_text(m["owner"], me) for m in facts["after"]] or ["None."]
    if facts["parked"]:
        out += ["", f"Not listed: {facts['parked']} dated item(s) in paused, reference or closed projects."]
    return "\n".join(out) + "\n"


def failure(today: str, reason: str) -> str:
    return (STAMP.format(today=today, result="failed", start="?", end="?", sources="none") + "\n"
            f"# Week ahead — {today}\n\n**FAILED:** {reason}\n")


def page(data: dict) -> str | None:
    template = fo.read(TEMPLATE)
    if DATA_SLOT not in template:
        return None
    return template.replace(DATA_SLOT, json.dumps(data, ensure_ascii=False, indent=1).replace("<", "\\u003c"), 1)


# ---------------------------------------------------------------- files

def write(out: Path, today: str, body: str, data: dict):
    out.mkdir(parents=True, exist_ok=True)
    for name in (f"weekly-{today}.md", "weekly-latest.md"):
        (out / name).write_text(body, encoding="utf-8", newline="\n")
    (out / "weekly-latest.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    html = page(data)
    if html is None:
        print(f"weekly: {TEMPLATE.name} missing or has no data slot; weekly-latest.html not written", file=sys.stderr)
    else:
        (out / "weekly-latest.html").write_text(html, encoding="utf-8", newline="\n")


def prune(out: Path, today: str, weeks: int) -> list[str]:
    cutoff = date.fromisoformat(today) - timedelta(weeks=weeks)
    removed = []
    for f in sorted(out.glob("weekly-*.md")):
        m = DATED.match(f.name)
        try:
            day = date.fromisoformat(m.group(1)) if m else None
        except ValueError:
            day = None
        if day and day < cutoff:
            f.unlink()
            removed.append(f.name)
    return removed


def last_ok(out: Path) -> str | None:
    m = STAMP_RE.match(fo.read(out / "weekly-latest.md"))
    return m.group(1) if m and m.group(2) == "ok" else None


# ---------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--registry", default=str(fo.DEFAULT_REGISTRY))
    ap.add_argument("--settings", default=str(bf.DEFAULT_SETTINGS))
    ap.add_argument("--out", default=str(fo.HUB / "_overview"))
    ap.add_argument("--today", help="YYYY-MM-DD, for testing")
    ap.add_argument("--time-off", default=str(bf.TIME_OFF))
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--scheduled", action="store_true", help="only if weekly_enabled, and not twice in one day")
    mode.add_argument("--catch-up", action="store_true",
                      help=f"only if weekly_enabled, and only if no weekly brief was written in the last {CATCH_UP_DAYS} days")
    args = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")
    today = args.today or date.today().isoformat()
    out = Path(args.out)
    settings, notes = read_settings(Path(args.settings))

    if (args.scheduled or args.catch_up) and not settings["weekly_enabled"]:
        print("weekly: not enabled in brief-settings.md (weekly_enabled); nothing written")
        return 0

    start, end = week_window(today)
    registry = Path(args.registry)
    try:
        entries = fo.read_registry(registry)
    except (OSError, UnicodeDecodeError) as exc:
        reason = f"registry {registry} could not be read: {getattr(exc, 'strerror', None) or exc}."
        write(out, today, failure(today, reason), {"schema": SCHEMA, "ok": False, "today": today, "reason": reason})
        print(f"weekly FAILED: {reason}", file=sys.stderr)
        return 1
    scope = fo.read_scope()
    included, uncategorized = fo.in_scope(entries, scope)
    if not included:
        reason = f"registry {registry} has no included projects" + (f" in this hub's scope ({', '.join(sorted(scope))})" if scope else "") + "."
        write(out, today, failure(today, reason), {"schema": SCHEMA, "ok": False, "today": today, "reason": reason})
        print(f"weekly FAILED: {reason}", file=sys.stderr)
        return 1
    if args.scheduled or args.catch_up:
        prior = last_ok(out)
        if prior and (prior == today if args.scheduled else (date.fromisoformat(today) - date.fromisoformat(prior)).days < CATCH_UP_DAYS):
            # Reused only while it covers the same projects: a project excluded since must not linger.
            if bf.built_from(out / "weekly-latest.json") == bf.covered(included):
                print(f"weekly: {out / 'weekly-latest.md'} is recent enough ({prior}); nothing written")
                return 0
            print("weekly: the registry's included projects changed since the last weekly brief; rebuilding")

    reach = (date.fromisoformat(end) + timedelta(days=AFTER_DAYS) - date.fromisoformat(today)).days
    projects = [fo.inspect(e, today, max(14, reach), fo.read_stale_days()) for e in included]
    time_off, off_notes = bf.read_time_off(Path(args.time_off))
    notes = notes + off_notes
    me = bf.read_me()
    scope_note = fo.scope_note(scope, uncategorized)
    facts = collect(projects, today, start, end, time_off, {})
    active = [p for p in projects if p.get("state") == "ok" and p["lifecycle"] == "active"]
    agenda_settings = bf.read_settings(Path(args.settings))[0]  # agenda_kinds; its notes belong to the daily brief
    meetings, clashes = bf.meeting_facts(active, today, time_off, agenda_settings)
    cs = cautions(projects, facts, meetings, clashes, start, end, today, time_off,
                  bf.AGENDA_KINDS[agenda_settings["agenda_kinds"]])
    days = day_rows(facts, meetings, start, end, time_off)
    details = project_details(projects, facts, meetings, start, end, settings["weekly_top_tasks"], me)
    body = render(facts, today, start, end, notes, scope_note, projects, cs, days, details, me, time_off)
    data = {"schema": SCHEMA, "ok": True, "today": today, "start": start, "end": end, "after_end": facts["after_end"],
            "covered": bf.covered(included),
            "hub": str(fo.HUB), "notes": notes, "scope": scope_note, "sources": bf.sources(projects), "me": me,
            "time_off": [t for t in time_off if t["end"] >= start and t["start"] <= facts["after_end"]],
            "cautions": cs, "days": days, "carried": facts["carried"], "projects": details, "after": facts["after"],
            "parked": facts["parked"]}
    write(out, today, body, data)
    removed = prune(out, today, settings["weekly_retention_weeks"])
    print(f"wrote {out / f'weekly-{today}.md'} and weekly-latest.md: week {start} to {end}, {len(facts['week'])} dated item(s), "
          f"{sum(1 for c in cs if c['level'] == 'high')} caution(s) needing attention"
          + (f"; pruned {len(removed)} older weekly brief(s)" if removed else ""))
    return 0


