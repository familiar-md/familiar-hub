#!/usr/bin/env python3
"""brief.py — a short daily brief across every registered familiar project. Read-only on projects.

    python scripts/brief.py                 # write _overview/brief-<today>.md and brief-latest.md
    python scripts/brief.py --catch-up      # same, only if enabled and today's brief is not there yet

Collects through `fleet_overview.py` (same registry, same per-project scripts, same fallbacks) and
renders one page: overdue milestones, startable tasks, milestones due soon, key dates further out
(to `lookahead_days`), cross-project date collisions and crowded weeks, projects that are stale or missing data, and a count per Lifecycle.
Settings come from `brief-settings.md` in the hub. Only `YYYY-MM-DD` dates count, as in the
per-project scripts; missing data is reported, never guessed.

Dated briefs older than `retention_days` are deleted. If the registry cannot be read, a one-line
failure brief is written and the exit code is 1, so a missed brief is visible. The scheduled entry
and the catch-up pass `--catch-up`, which does nothing when `enabled` is not `yes` or when
`brief-latest.md` already holds a successful brief for today built from the same included projects
(`covered` in `brief-latest.json`); a project excluded or added since then rebuilds it. Standard
library only.
"""

