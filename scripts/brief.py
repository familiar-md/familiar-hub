DEFAULT_SETTINGS = fo.HUB / "brief-settings.md"
DEFAULTS = {"enabled": False, "retention_days": 14, "horizon_days": 14, "lookahead_days": 42, "top_per_project": 5,
            "agenda_kinds": "none", "agenda_lead_days": 2}
MAX_DAYS = 366  # sanity limit for horizon_days and lookahead_days
MAX_LEAD = 10  # cap for agenda_lead_days (business days)
AGENDA_KINDS = {"client": ("client",), "internal": ("internal",), "both": ("client", "internal"), "none": ()}
AGENDA_LABEL = {"client": "Client", "internal": "Internal", "both": "Client and internal", "none": "No"}
SETTING = re.compile(r"^\s*[-*]?\s*`?(enabled|retention_days|horizon_days|lookahead_days|top_per_project|agenda_kinds|"
                     r"agenda_lead_days)`?\s*:\s*`?([^`\s]+)`?\s*$")
SNOOZES = "agenda-snoozes.md"  # hub-local "Remind me on" lines, written by apply_change.py
SNOOZE = re.compile(r"^\s*(.+?)\s*\|\s*([SX]-\d+)\s+(\d{4}-\d{2}-\d{2})\s*\|\s*remind\s+(\d{4}-\d{2}-\d{2})\s*$",
                    re.IGNORECASE)
BRIEF_STAMP = "<!-- brief: {today} {result}; generated by scripts/brief.py; do not edit. Sources: {sources} -->"
BRIEF_STAMP_RE = re.compile(r"<!-- brief: (\d{4}-\d{2}-\d{2}) (ok|failed);")
DATED = re.compile(r"^brief-(\d{4}-\d{2}-\d{2})\.md$")
CURRENT = ("active",)
TEMPLATE = Path(__file__).resolve().parent / "brief-template.html"
DATA_SLOT = "__BRIEF_DATA__"
TIMELINE_WEEKS = 6  # the page timeline: Monday of this week through Friday of week 6, whatever today is
HEAVY_WEEK = 3  # the page flags a timeline week holding this many deliverables or more, across the projects shown
DATA_SCHEMA = 1  # bump when brief-latest.json changes shape; the template checks it
NOW_DAYS = 3  # a milestone due within this many days is "now"
AT_RISK = re.compile(r"\bat[ -]risk\b", re.IGNORECASE)
SIGNATURE = re.compile(r"\*\*familiar signature:\*\*\s*`?([^`\n]+?)`?\s*$", re.MULTILINE | re.IGNORECASE)
GLOBAL_PREFS = Path.home() / ".familiar" / "user-preferences.md"
ME = re.compile(r"^\s*[-*]?\s*`?me`?\s*:\s*`?([^`\n]*?)`?\s*$", re.MULTILINE)
# The user's own time off, shared by every hub on this machine: `~/.familiar/time-off.md`, beside the registry.
TIME_OFF = fo.DEFAULT_REGISTRY.parent / "time-off.md"
PERIOD = re.compile(r"^\s*[-*]\s+(\d{4}-\d{2}-\d{2})(?:\s*(?:to|through|–|-)\s*(\d{4}-\d{2}-\d{2}))?"
                    r"\s*(?:—\s*(.*?))?\s*$", re.IGNORECASE)
DATED_LINE = re.compile(r"^\s*[-*]\s+\d{4}-\d{2}-\d{2}")


# ---------------------------------------------------------------- settings

def read_settings(path: Path) -> tuple[dict, list[str]]:
    """(settings, notes). Every problem falls back to the default and is noted, never fatal."""
    settings, notes = dict(DEFAULTS), []
    if not path.is_file():
        return settings, [f"`{path.name}` not found; using defaults."]
    seen = set()
    for line in fo.read(path).splitlines():
        m = SETTING.match(line)
        if not m or m.group(1) in seen:
            continue
        key, raw = m.group(1), m.group(2).strip().lower()
        seen.add(key)
        if key == "enabled":
            if raw in ("yes", "true", "on"):
                settings[key] = True
            elif raw not in ("no", "false", "off"):
                notes.append(f"`enabled: {raw}` is not yes or no; treated as no.")
            continue
        if key == "agenda_kinds":
            if raw in AGENDA_KINDS:
                settings[key] = raw
            else:
                notes.append(f"`agenda_kinds: {raw}` is not client, internal, both or none; using none.")
            continue
        try:
            value = int(raw)
            if value < 1:
                raise ValueError
        except ValueError:
            notes.append(f"`{key}: {raw}` is not a positive whole number; using {DEFAULTS[key]}.")
            continue
        if key in ("horizon_days", "lookahead_days") and value > MAX_DAYS:
            notes.append(f"`{key}: {value}` is over {MAX_DAYS}; using {MAX_DAYS}.")
            value = MAX_DAYS
        if key == "agenda_lead_days" and value > MAX_LEAD:
            notes.append(f"`agenda_lead_days: {value}` is over {MAX_LEAD}; using {MAX_LEAD}.")
            value = MAX_LEAD
        settings[key] = value
    if settings["lookahead_days"] < settings["horizon_days"]:
        notes.append(f"`lookahead_days` is shorter than `horizon_days`; using {settings['horizon_days']} for both.")
        settings["lookahead_days"] = settings["horizon_days"]
    return settings, notes


def timeline_end_days(today: str) -> int:
    """Days from `today` to the Friday that closes the page timeline's last week."""
    d = date.fromisoformat(today)
    return (d - timedelta(days=d.weekday())).toordinal() + 7 * (TIMELINE_WEEKS - 1) + 4 - d.toordinal()


def signature(root: str, fallback: Path = None) -> str:
    """The project's familiar signature, as its bind line uses it: the project's own
    `5-System/user-preferences.md`, else the shared `~/.familiar/user-preferences.md`, else ''."""
    for path in (Path(root) / "5-System" / "user-preferences.md", fallback or GLOBAL_PREFS):
        m = SIGNATURE.search(fo.read(path))
        if m and m.group(1).strip():
            return m.group(1).strip()
    return ""


def signature_notes(projects: list[dict], fallback: Path = None) -> list[str]:
    """A note for each signature that labels more than one project, and one for projects that show none.
    A project with no signature of its own shows the default, so all such projects share that key."""
    m = SIGNATURE.search(fo.read(fallback or GLOBAL_PREFS))
    default = m.group(1).strip() if m else ""
    by_key = {}
    for p in projects:
        by_key.setdefault(signature(p["path"], fallback), []).append(p["name"])
    notes = []
    for key, names in sorted(by_key.items()):
        if key and len(names) > 1:
            notes.append(f"`{key}`{' (the default)' if key == default else ''} labels {', '.join(names)}; give each its "
                         "own with `/system-settings` → Preferences inside the project.")
    if by_key.get(""):
        notes.append(f"No signature: {', '.join(by_key[''])}.")
    return notes


def read_me(path: Path = None) -> list[str]:
    """The names that mean the user in an Owner field, from `hub-settings.md` → `me` (comma-separated)."""
    m = ME.search(fo.read(path or fo.HUB_SETTINGS))
    names = [n.strip() for n in m.group(1).split(",")] if m else []
    return [n for n in names if n and n.lower() not in fo.UNSET]


def read_time_off(path: Path) -> tuple[list[dict], list[str]]:
    """(periods, notes) from the time-off file. A missing file is no time off. A dated line that cannot be
    read is noted, never guessed."""
    periods, notes = [], []
    for n, line in enumerate(fo.read(path).splitlines(), 1):
        m = PERIOD.match(line)
        if not m:
            if DATED_LINE.match(line):
                notes.append(f"`{path.name}` line {n} not read (write `- YYYY-MM-DD to YYYY-MM-DD — note`).")
            continue
        start, end = m.group(1), m.group(2) or m.group(1)
        try:
            if date.fromisoformat(end) < date.fromisoformat(start):
                raise ValueError
        except ValueError:
            notes.append(f"`{path.name}` line {n} has an invalid date or range; not read.")
            continue
        periods.append({"start": start, "end": end, "note": (m.group(3) or "").strip()})
    return sorted(periods, key=lambda p: p["start"]), notes


def off_on(periods: list[dict], day: str) -> dict | None:
    return next((p for p in periods if p["start"] <= day <= p["end"]), None)


def span(p: dict) -> str:
    return p["start"] + ("" if p["end"] == p["start"] else f" to {p['end']}") + (f" — {p['note']}" if p["note"] else "")


def read_snoozes(path: Path, today: str) -> dict:
    """{(project, meeting ID, meeting date): remind date} from the hub-local `_overview/agenda-snoozes.md`.
    A line whose meeting has passed, or that cannot be read, is ignored (the file is not rewritten)."""
    found = {}
    for line in fo.read(path).splitlines():
        m = SNOOZE.match(line)
        if m and m.group(3) >= today:
            found[(m.group(1).lower(), m.group(2).upper(), m.group(3))] = m.group(4)
    return found


def read_applied(out: Path, today: str, keep_days: int = 14) -> list[dict]:
    """What `apply_change.py apply` changed lately, from its `applied-*.json` records: one entry per applied line,
    keyed as its batch check keys it (project, kind, ID, `on`), with the time it was applied. The page drops a
    mark applied after it was made, which it cannot otherwise see for a task's date (task rows carry none)."""
    cutoff = (date.fromisoformat(today) - timedelta(days=keep_days)).isoformat()
    found = []
    for f in sorted(out.glob("applied-*.json")):
        m = re.match(r"^applied-(\d{4}-\d{2}-\d{2})_(\d{2})(\d{2})(\d{2})\.json$", f.name)
        if not m or m.group(1) < cutoff:
            continue
        try:
            done = json.loads(f.read_text(encoding="utf-8")).get("applied", [])
        except (OSError, ValueError, AttributeError):
            continue
        at = f"{m.group(1)}T{m.group(2)}:{m.group(3)}:{m.group(4)}"
        for item in done if isinstance(done, list) else []:
            try:
                found.append({"project": item["project"].lower(), "kind": item["kind"], "id": item["id"].upper(),
                              "on": (item.get("meeting") or {}).get("on", ""), "at": at})
            except (KeyError, AttributeError, TypeError):
                continue
    return found


def business_days_before(today: str, day: str, time_off: list[dict]) -> int:
    """Working days from today up to, not including, `day`: Monday to Friday less the user's time off.
    Public holidays are not known to the hub."""
    d, end, n = date.fromisoformat(today), date.fromisoformat(day), 0
    while d < end:
        if d.weekday() < 5 and not off_on(time_off, d.isoformat()):
            n += 1
        d += timedelta(days=1)
    return n


def agenda_status(agenda: dict | None) -> str:
    """set | standing | none needed | not set, from the occurrence's `agenda` (meetings_view.py). A standing
    list counts as set (D3); the page tags it "standing only"."""
    if not agenda:
        return "not set"
    if agenda.get("none"):
        return "none needed"
    return "standing" if agenda.get("from") == "standing" else "set"


def mark_agendas(rows: list[dict], today: str, time_off: list[dict], settings: dict | None, snoozes: dict | None) -> None:
    """Adds `agenda_status`, `agenda_due` and `agenda_remind` to each meeting row. A meeting of a kind chosen in
    `agenda_kinds` with no agenda is due once it is `agenda_lead_days` business days away or closer, unless a
    hub-local reminder is set for a later day; on the reminder's day it is due whatever the lead. Derived each
    run, never stored, never on the timeline."""
    settings = settings or DEFAULTS
    kinds = AGENDA_KINDS.get(settings.get("agenda_kinds", "none"), ())
    lead = settings.get("agenda_lead_days", DEFAULTS["agenda_lead_days"])
    for r in rows:
        r["agenda_status"] = agenda_status(r.get("agenda"))
        remind = (snoozes or {}).get((r["project"].lower(), r["ref"].upper(), r["date"]), "")
        r["agenda_remind"] = remind
        r["agenda_due"] = bool(not r["parked"] and r["kind"] in kinds and r["agenda_status"] == "not set" and (
            remind <= today if remind else business_days_before(today, r["date"], time_off) <= lead))


# ---------------------------------------------------------------- rendering

def age(day: str | None, today: str) -> int | None:
    try:
        return (date.fromisoformat(today) - date.fromisoformat(day)).days
    except (TypeError, ValueError):
        return None


def sources(projects) -> str:
    return "; ".join(p["name"] + " " + ", ".join(f"{k} r{v}" for k, v in p["revisions"].items())
                     for p in projects if p.get("revisions"))


def windows(projects: list[dict], today: str, settings: dict):
    """(horizon, lookahead, overdue, soon, ahead): the date cut-offs and the milestone rows in each window."""
    horizon = (date.fromisoformat(today) + timedelta(days=settings["horizon_days"])).isoformat()
    lookahead = (date.fromisoformat(today) + timedelta(days=settings["lookahead_days"])).isoformat()
    rows = fo.dated_rows(projects)
    overdue = [r for r in rows if r[1] == "overdue"]
    soon = [r for r in rows if r[1] == "upcoming" and r[0] <= horizon]
    ahead = [r for r in rows if r[1] == "upcoming" and horizon < r[0] <= lookahead]
    return horizon, lookahead, overdue, soon, ahead


def problems(p: dict) -> list[str]:
    """A readable project's data problems, less the stale/undated flag the brief reports on its own."""
    # A project copy older than --window is expected until the next fleet carry; not a data problem.
    return [f for f in p["flags"] if not f.startswith(("snapshot has no last-updated",
                                                       "timeline: project copy predates --window"))]


def meeting_facts(projects: list[dict], today: str, time_off: list[dict] = (), settings: dict | None = None,
                  snoozes: dict | None = None) -> tuple[list[dict], list[str]]:
    """(meetings, clashes): every planned meeting the projects reported for the window, in date and time order,
    and the fleet-wide overlaps among those of active projects. Meetings come from each project's own
    meetings.md through its meetings_view.py; nothing is guessed. `ref` is what an edit must name: the
    series for a series date, the meeting itself for a one-off. Agenda fields come from `mark_agendas`; without
    `settings` no meeting is agenda-due."""
    rows = []
    for p in projects:
        found = p.get("meetings")
        if p.get("state") != "ok" or not found:
            continue
        for o in found.get("occurrences", []):
            away = off_on(time_off, o["date"])
            rows.append({"date": o["date"], "days": (date.fromisoformat(o["date"]) - date.fromisoformat(today)).days,
                         "start": o["start"], "end": o["end"], "project": p["name"], "meeting": o["meeting"],
                         "kind": o["kind"], "shape": o["kind"] + "-meeting", "attendees": o["attendees"],
                         "milestone": "" if o["milestone"] in ("", "\u2014", "-") else o["milestone"],
                         "ref": o["series"] or o["id"], "id": o["id"], "series": o["series"], "source": o["source"],
                         "moved_from": o["moved_from"], "note": o["note"], "parked": p["lifecycle"] != "active",
                         "time_off": span(away) if away else "", "overlaps": [], "agenda": o.get("agenda")})
    rows.sort(key=lambda r: (r["date"], r["start"], r["project"], r["meeting"]))
    mark_agendas(rows, today, time_off, settings, snoozes)
    clashes = []
    live = [r for r in rows if not r["parked"]]
    for i, a in enumerate(live):
        for b in live[i + 1:]:
            if b["date"] != a["date"]:
                break
            if b["start"] < (a["end"] or a["start"]) and a["start"] < (b["end"] or b["start"]):
                clashes.append(f"{a['date']}: {a['project']} {a['meeting']} ({a['start']}-{a['end']}) overlaps "
                               f"{b['project']} {b['meeting']} ({b['start']}-{b['end']})")
                a["overlaps"].append(b["project"] + " " + b["meeting"])
                b["overlaps"].append(a["project"] + " " + a["meeting"])
    return rows, clashes


def render(projects: list[dict], today: str, settings: dict, notes: list[str], scope: str = "",
           time_off: list[dict] = (), snoozes: dict | None = None, sig_notes: list[str] = ()) -> str:
    horizon, lookahead, overdue, soon, ahead = windows(projects, today, settings)
    meetings, meeting_clashes = meeting_facts(projects, today, time_off, settings, snoozes)
    ok = [p for p in projects if p.get("state") == "ok"]

    counts = {}
    for p in ok:
        counts[p["lifecycle"]] = counts.get(p["lifecycle"], 0) + 1
    life = " · ".join(f"{s} {counts[s]}" for s in fo.ORDER if s in counts)
    unreadable = len(projects) - len(ok)

    stale = fo.stale_lines(ok)
    out = [BRIEF_STAMP.format(today=today, result="ok", sources=sources(projects)),
           f"# Fleet brief — {today}", "",
           f"{len(projects)} project(s) included; {len(ok)} readable"
           + (f", {unreadable} not readable" if unreadable else "") + ". "
           f"Lifecycle: {life or 'none readable'}. "
           f"{len(overdue)} overdue, {len(soon)} due by {horizon}, {len(ahead)} more by {lookahead}.", "",
           *([scope, ""] if scope else [])]
    if stale:
        out += [f"## STALE: do not rely on these projects' lines below", "",
                f"Active projects whose snapshot is older than {fo.read_stale_days()} days "
                "(`stale_days` in `hub-settings.md`) or has no last-updated date. If a project is paused or "
                "finished, run `python scripts/fleet_overview.py --set-lifecycle NAME paused|reference|closed`.", "",
                *stale, ""]
    if notes:
        out += ["Settings: " + " ".join(notes), ""]
    if sig_notes:
        out += ["Signatures: " + " ".join(sig_notes), ""]

    def where(p):
        return f"**{p['name']}** ({fo.label(p)})"

    out += ["## Overdue and still open", ""]
    out += [f"- {due} — {where(p)} — {m['name']} — {m['status'] or 'status not set'}"
            for due, _, p, m in overdue] or ["None."]

    if AGENDA_KINDS.get(settings.get("agenda_kinds", "none")):  # only when agenda reminders are on
        out += ["", "## Agendas to set", "",
                f"{AGENDA_LABEL[settings['agenda_kinds']]} meetings with no agenda, {settings['agenda_lead_days']} business "
                "day(s) ahead or closer (or on a reminder day you set). Set one, or mark it not needed, from the brief "
                "page or in the project.", ""]
        out += [f"- {m['date']} {m['start']} — **{m['project']}** — {m['meeting']} ({m['ref']}, {m['kind']})"
                + (f" — you asked to be reminded today" if m["agenda_remind"] else "")
                for m in meetings if m["agenda_due"]] or ["None."]

    out += ["", f"## Due in the next {settings['horizon_days']} days", ""]
    out += [f"- {due} — {where(p)} — {m['name']} — {m['status'] or 'status not set'}"
            + (f" — {m['owner']}" if m.get("owner") else "") for due, _, p, m in soon] or ["None."]

    out += ["", f"## Key dates ahead, to {lookahead}", "",
            "Every open dated milestone after the window above, so work that starts now can see its deadline.", ""]
    out += [f"- {due} — {where(p)} — {m['name']} — {m['status'] or 'status not set'}"
            + (f" — {m['owner']}" if m.get("owner") else "") for due, _, p, m in ahead] or ["None."]

    if meetings:  # only when a project keeps meetings.md, so a fleet without any sees no new section
        out += ["", f"## Meetings, next {settings['horizon_days']} days", "",
                "From each project's `4-Trackers/meetings.md`. Notes only: the hub does not touch your calendar.", ""]
        near = [m for m in meetings if m["date"] <= horizon and not m["parked"]]
        for m in near:
            hours = f"{m['start']}-{m['end']}" if m["end"] else m["start"]
            bits = [m["kind"]] + ([f"moved from {m['moved_from']}"] if m["source"] == "moved" else []) \
                + (["extra"] if m["source"] == "extra" else []) + ([m["milestone"]] if m["milestone"] else []) \
                + (["you are off"] if m["time_off"] else [])
            agenda = {"set": "agenda set", "standing": "standing agenda only", "none needed": "no agenda needed",
                      "not set": "AGENDA NOT SET" if m["agenda_due"] else ""}[m["agenda_status"]]
            out.append(f"- {m['date']} {hours} — **{m['project']}** — {m['meeting']} ({', '.join(bits)})"
                       + (f" — {', '.join(m['attendees'])}" if m["attendees"] else "") + (f" — {agenda}" if agenda else ""))
        if not near:
            out.append("None.")
        soon_clashes = [c for c in meeting_clashes if c[:10] <= horizon]
        out += ["", f"Meeting clashes, next {settings['horizon_days']} days:"] + ([f"- {c}" for c in soon_clashes] or ["- None."])

    away = [t for t in time_off if t["end"] >= today and t["start"] <= lookahead]
    if away:  # only when there is some, so a user without the file sees no new section
        out += ["", f"## Your time off, to {lookahead}", "", f"From `{TIME_OFF.name}` beside the registry.", ""]
        for t in away:
            out.append(f"- {span(t)}")
            out += [f"  - due then: {due} — {where(p)} — {m['name']}"
                    for due, _, p, m in soon + ahead if t["start"] <= due <= t["end"]]

    out += ["", f"## Collisions, to {lookahead}", ""]
    by_day = {}
    for due, _, p, m in soon + ahead:
        by_day.setdefault(due, set()).add(p["name"])
    clashes = [f"- {d}: {', '.join(sorted(n))}" for d, n in sorted(by_day.items()) if len(n) >= 2]
    crowded = [f"- {c}" for c in fo.crowded_weeks(soon + ahead)]
    out += ["Same day, 2+ projects:"] + (clashes or ["- None."])
    out += ["", "Crowded weeks, 3+ projects:"] + (crowded or ["- None."])

    top = settings["top_per_project"]
    out += ["", f"## Startable now (top {top} per active project)", ""]
    shown, hidden = 0, 0
    for p in ok:
        if "frontier" not in p:
            continue
        if p["lifecycle"] not in CURRENT:
            hidden += len(p["frontier"])
            continue
        if not p["frontier"]:
            continue
        shown += 1
        more = len(p["frontier"]) - top
        out.append(f"- {where(p)} — {len(p['frontier'])} startable, {len(p['blocked'])} blocked")
        for t in p["frontier"][:top]:
            ident = f"{t['id']} " if t.get("id") else ""
            out.append(f"  - {ident}{t['title']}")
        if more > 0:
            out.append(f"  - …and {more} more (see `frontier.md` after `fleet_overview.py`)")
    if not shown:
        out.append("None.")
    if hidden:
        out += ["", f"Not listed: {hidden} startable task(s) in paused, reference or closed projects."]

    out += ["", "## Other data problems", ""]
    flagged = []
    for p in projects:
        if p.get("state") != "ok":
            flagged.append(f"- **{p['name']}** — not readable: {'; '.join(p['flags'])}")
            continue
        bits = problems(p)  # stale and undated projects are reported at the top
        if bits:
            flagged.append(f"- {where(p)} — " + "; ".join(bits))
    out += flagged or ["None."]

    out += ["", "## Data age", "", "| project | lifecycle | snapshot updated | age (days) |", "|---|---|---|---|"]
    for p in ok:
        days = age(p.get("last_updated"), today)
        out.append(f"| {p['name']} | {p['lifecycle']} | {p.get('last_updated') or 'not recorded'} | "
                   f"{'?' if days is None else days} |")
    return "\n".join(out) + "\n"


def failure(today: str, reason: str) -> str:
    return (BRIEF_STAMP.format(today=today, result="failed", sources="none") + "\n"
            f"# Fleet brief — {today}\n\n**FAILED:** {reason}\n")


# ---------------------------------------------------------------- data and page

def urgency(p: dict, kind: str, days: int, status: str) -> str:
    """now | soon | later for an active project's milestone; parked for any other lifecycle. Overdue or
    due within NOW_DAYS is now; at risk, or inside the horizon, is soon."""
    if p["lifecycle"] != "active":
        return "parked"
    if kind == "overdue" or days <= NOW_DAYS:
        return "now"
    return "soon" if AT_RISK.search(status) else "later"


def milestone_type(p: dict, m: dict, cache: dict) -> str:
    """The milestone's `Type` cell. A project at core 0.4.8+ puts it in the timeline JSON; an older one is read
    from its own `timeline.md` with the hub's bundled parser, matched by ID, then by name."""
    if "type" in m:
        return m.get("type") or ""
    if p["name"] not in cache:
        sys.path.insert(0, str(fo.BUNDLED))
        try:
            import timeline_views as tv  # noqa: E402  the bundled parser, one definition of a milestone row
        finally:
            sys.path.pop(0)
        rows = tv.parse(fo.read(Path(p["path"]) / "4-Trackers" / "timeline.md"))
        cache[p["name"]] = ({r["id"]: r["type"] for r in rows if r["has_id"]}, {r["name"]: r["type"] for r in rows})
    by_id, by_name = cache[p["name"]]
    return by_id.get(m.get("id") or "", by_name.get(m.get("name") or "", ""))


def shape(kind: str) -> str:
    """The page's timeline marker: deliverable star, client meeting triangle, internal meeting circle, else diamond."""
    k = kind.strip().lower()
    if "client meeting" in k:
        return "client-meeting"
    if "internal meeting" in k:
        return "internal-meeting"
    return "deliverable" if k.startswith("deliverable") else "other"


def risk_reason(p: dict, m: dict) -> str:
    """Why a milestone is at risk, only from what the project wrote: a note under the timeline table that
    names the milestone (by ID, or by name) and mentions risk, else the bracketed remark in its Due cell.
    Empty when neither exists; never inferred."""
    notes = [line.strip(" -*>") for line in fo.read(Path(p["path"]) / "4-Trackers" / "timeline.md").splitlines()
             if line.strip() and not line.lstrip().startswith("|") and re.search(r"\brisk", line, re.IGNORECASE)]
    ident = m.get("id") if re.fullmatch(r"[A-Z]{1,5}-\d+", m.get("id") or "") else None
    for line in notes:
        if (ident and re.search(rf"\b{re.escape(ident)}\b", line)) or m["name"].lower() in line.lower():
            return line
    remark = re.search(r"\((.+)\)\s*$", m.get("when") or "")
    return remark.group(1).strip() if remark else ""


DONE = ("done", "complete", "completed")  # statuses drawn greyed on the timeline; "not applicable" is not completed work


def completed_milestones(projects: list[dict], today: str, lookahead: str, cache: dict, since_days: int = 7) -> list[dict]:
    """Milestones the projects mark done, dated from a week back to the lookahead, for the page's timeline only
    (greyed, so finished work stays visible). Read from each timeline.md with the bundled parser; a project whose
    timeline cannot be read adds none."""
    sys.path.insert(0, str(fo.BUNDLED))
    try:
        import timeline_views as tv  # noqa: E402  the bundled parser, one definition of a milestone row
    finally:
        sys.path.pop(0)
    since = (date.fromisoformat(today) - timedelta(days=since_days)).isoformat()
    out = []
    for p in projects:
        if p.get("state") != "ok" or p["lifecycle"] != "active":
            continue
        try:
            rows = tv.parse(fo.read(Path(p["path"]) / "4-Trackers" / "timeline.md"))
        except Exception:  # an unreadable timeline is reported elsewhere; here it only adds nothing
            continue
        for r in rows:
            if not r["dated"] or not r["status"].lower().startswith(DONE):
                continue
            due = r["due"].isoformat()
            if since <= due <= lookahead:
                out.append({"due": due, "project": p["name"], "name": r["name"], "status": r["status"],
                            "type": r["type"], "shape": shape(r["type"])})
    return sorted(out, key=lambda c: (c["due"], c["project"], c["name"]))


def milestone_fact(due: str, kind: str, p: dict, m: dict, window: str, today: str, time_off: list[dict], types: dict) -> dict:
    """One open milestone as the brief's data row; `window` is overdue, soon or ahead."""
    days = (date.fromisoformat(due) - date.fromisoformat(today)).days
    level = urgency(p, kind, days, m.get("status") or "")
    mtype = milestone_type(p, m, types)
    if level == "later" and window == "soon":
        level = "soon"
    return {"due": due, "days": days, "window": window, "urgency": level,
            "at_risk": bool(AT_RISK.search(m.get("status") or "")),
            "risk_reason": risk_reason(p, m) if AT_RISK.search(m.get("status") or "") else "",
            "project": p["name"], "id": m.get("id") if re.fullmatch(r"[A-Z]{1,5}-\d+", m.get("id") or "") else "",
            "name": m["name"], "status": m.get("status") or "",
            "owner": m.get("owner") or "", "track": m.get("track") or "",
            "type": mtype, "shape": shape(mtype),
            "time_off": span(off_on(time_off, due)) if off_on(time_off, due) else ""}


def full_span(wide: list[dict], today: str, time_off: list[dict]) -> dict:
    """The whole-fleet timeline for the page's collapsed "Full timeline": every dated milestone of the active
    projects, open and done, from the earliest to the latest, read with the widest window (`MAX_DAYS`).
    Meetings are counted per week (Monday date), not listed. Page only: the markdown brief is unchanged."""
    types: dict = {}
    active = [p for p in wide if p.get("state") == "ok" and p["lifecycle"] == "active"]
    open_rows = [milestone_fact(due, kind, p, m, "overdue" if kind == "overdue" else "ahead", today, time_off, types)
                 for due, kind, p, m in fo.dated_rows(active)]
    last = max([r["due"] for r in open_rows] + [today])
    done = completed_milestones(active, today, last, types, since_days=36500)
    dates = [r["due"] for r in open_rows] + [c["due"] for c in done] + [today]
    first, last = min(dates), max(dates)
    weeks: dict = {}
    for mt in meeting_facts(active, today, time_off)[0]:
        if mt["date"] > last:
            continue
        d = date.fromisoformat(mt["date"])
        monday = (d - timedelta(days=d.weekday())).isoformat()
        weeks.setdefault(monday, {"internal": 0, "client": 0})[mt["kind"]] += 1
    return {"start": first, "end": last, "milestones": open_rows, "done": done,
            "time_off": [t for t in time_off if t["end"] >= first and t["start"] <= last], "meeting_weeks": weeks}


def meeting_urgency(m: dict, horizon: str) -> str:
    """A meeting's list on the page, in the milestones' windows: now within NOW_DAYS, soon to the horizon, later
    after it, parked for a project that is not active. An agenda-due meeting is now whatever its date."""
    if m["parked"]:
        return "parked"
    if m["agenda_due"] or m["days"] <= NOW_DAYS:
        return "now"
    return "soon" if m["date"] <= horizon else "later"


def data(projects: list[dict], today: str, settings: dict, notes: list[str], scope: str = "",
         time_off: list[dict] = (), me: list[str] = (), wide: list[dict] | None = None,
         snoozes: dict | None = None, applied: list[dict] | None = None, sig_notes: list[str] = ()) -> dict:
    """The same facts as `render`, as data for `brief-latest.json` and the page. No new judgement beyond
    `urgency`, which is fixed here so every host shows the same order."""
    horizon, lookahead, overdue, soon, ahead = windows(projects, today, settings)
    milestones, types = [], {}
    for window, rows in (("overdue", overdue), ("soon", soon), ("ahead", ahead)):
        for due, kind, p, m in rows:
            milestones.append(milestone_fact(due, kind, p, m, window, today, time_off, types))
    by_day = {}
    for due, _, p, m in soon + ahead:
        by_day.setdefault(due, set()).add(p["name"])
    meetings, meeting_clashes = meeting_facts(projects, today, time_off, settings, snoozes)
    for m in meetings:
        m["urgency"] = meeting_urgency(m, horizon)
    out = []
    for p in projects:
        entry = {"name": p["name"], "signature": signature(p["path"]), "state": p.get("state"), "lifecycle": p["lifecycle"],
                 "stale": p.get("stale"), "label": fo.label(p)}
        if p.get("state") != "ok":
            entry["problems"] = p["flags"]
            out.append(entry)
            continue
        entry.update({"last_updated": p.get("last_updated"), "age_days": age(p.get("last_updated"), today),
                      "stale_text": fo.stale_text(p) if p.get("stale") else "",
                      "status": p.get("status"), "next_milestones": p.get("next_milestones"),
                      "startable": p.get("frontier", []), "blocked": p.get("blocked", []),
                      "tasks_read": "frontier" in p, "problems": problems(p)})
        out.append(entry)
    return {"schema": DATA_SCHEMA, "ok": True, "today": today, "horizon": horizon, "lookahead": lookahead,
            "settings": {k: settings[k] for k in ("horizon_days", "lookahead_days", "top_per_project",
                                                  "agenda_kinds", "agenda_lead_days")},
            "now_days": NOW_DAYS, "timeline_weeks": TIMELINE_WEEKS, "heavy_week": HEAVY_WEEK, "hub": str(fo.HUB), "notes": notes, "signature_notes": list(sig_notes), "scope": scope, "sources": sources(projects), "me": list(me),
            "time_off": [t for t in time_off if t["end"] >= today and t["start"] <= lookahead],
            "milestones": milestones, "completed": completed_milestones(projects, today, lookahead, types),
            "meetings": meetings, "meeting_clashes": meeting_clashes, "projects": out, "applied": applied or [],
            "full": full_span(wide, today, time_off) if wide else None,
            "collisions": [{"date": d, "projects": sorted(n)} for d, n in sorted(by_day.items()) if len(n) >= 2],
            "crowded_weeks": fo.crowded_weeks(soon + ahead)}


def failure_data(today: str, reason: str) -> dict:
    return {"schema": DATA_SCHEMA, "ok": False, "today": today, "reason": reason}


def page(facts: dict) -> str | None:
    """The fixed template with this brief's data pasted in, or None when the template is missing. The
    data sits inside the page because a browser opening a local file will not fetch a file beside it."""
    template = fo.read(TEMPLATE)
    if DATA_SLOT not in template:
        return None
    blob = json.dumps(facts, ensure_ascii=False, indent=1).replace("<", "\\u003c")
    return template.replace(DATA_SLOT, blob, 1)


# ---------------------------------------------------------------- files

def write(out: Path, today: str, body: str, facts: dict):
    out.mkdir(parents=True, exist_ok=True)
    for name in (f"brief-{today}.md", "brief-latest.md"):
        (out / name).write_text(body, encoding="utf-8", newline="\n")
    (out / "brief-latest.json").write_text(json.dumps(facts, ensure_ascii=False, indent=2) + "\n",
                                           encoding="utf-8", newline="\n")
    html = page(facts)
    if html is None:
        print(f"brief: {TEMPLATE.name} missing or has no data slot; brief-latest.html not written", file=sys.stderr)
    else:
        (out / "brief-latest.html").write_text(html, encoding="utf-8", newline="\n")


def prune(out: Path, today: str, keep_days: int) -> list[str]:
    cutoff = date.fromisoformat(today) - timedelta(days=keep_days)
    removed = []
    for f in sorted(out.glob("brief-*.md")):
        m = DATED.match(f.name)
        if not m:
            continue
        try:
            day = date.fromisoformat(m.group(1))
        except ValueError:
            continue
        if day < cutoff:
            f.unlink()
            removed.append(f.name)
    return removed


def done_today(out: Path, today: str) -> bool:
    m = BRIEF_STAMP_RE.match(fo.read(out / "brief-latest.md"))
    return bool(m) and m.group(1) == today and m.group(2) == "ok"


def covered(included: list[dict]) -> list[str]:
    """The projects a brief is built from, recorded in its JSON so a later catch-up can compare."""
    return sorted(e["name"] for e in included)


def built_from(path: Path) -> list[str] | None:
    """The `covered` list of an earlier brief's JSON; None when it has none (a brief written before this check)."""
    try:
        names = json.loads(fo.read(path)).get("covered")
    except (ValueError, AttributeError):
        return None
    return sorted(names) if isinstance(names, list) else None


# ---------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--registry", default=str(fo.DEFAULT_REGISTRY))
    ap.add_argument("--settings", default=str(DEFAULT_SETTINGS))
    ap.add_argument("--out", default=str(fo.HUB / "_overview"))
    ap.add_argument("--today", help="YYYY-MM-DD, for testing")
    ap.add_argument("--time-off", default=str(TIME_OFF), help="the user's time-off file (default: beside the registry)")
    ap.add_argument("--catch-up", action="store_true",
                    help="only if enabled, and only if today's brief has not been written yet")
    args = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")
    today = args.today or date.today().isoformat()
    out = Path(args.out)
    settings, notes = read_settings(Path(args.settings))

    if args.catch_up and not settings["enabled"]:
        print("brief: not enabled in brief-settings.md; nothing written")
        return 0

    registry = Path(args.registry)
    try:
        entries = fo.read_registry(registry)
    except (OSError, UnicodeDecodeError) as exc:
        reason = f"registry {registry} could not be read: {getattr(exc, 'strerror', None) or exc}."
        if not registry.exists():
            reason += (" Create it from the hub with `python scripts/fleet_overview.py --discover "
                       "<folder holding your projects> --apply`.")
        write(out, today, failure(today, reason), failure_data(today, reason))
        print(f"brief FAILED: {reason}", file=sys.stderr)
        return 1
    scope = fo.read_scope()
    included, uncategorized = fo.in_scope(entries, scope)
    if not included:
        where = f" in this hub's scope ({', '.join(sorted(scope))})" if scope else ""
        reason = (f"registry {registry} has no included projects{where} (no `| name | path | ... |` rows "
                  "with included = yes" + (" and a matching category" if scope else "") + ").")
        write(out, today, failure(today, reason), failure_data(today, reason))
        print(f"brief FAILED: {reason}", file=sys.stderr)
        return 1
    # Today's brief is reused only while it covers the same projects. A project set `included: no` since
    # it was written would otherwise stay in brief-latest.* until tomorrow.
    if args.catch_up and done_today(out, today):
        if built_from(out / "brief-latest.json") == covered(included):
            print(f"brief: {out / 'brief-latest.md'} is already today's; nothing written")
            return 0
        print("brief: the registry's included projects changed since today's brief; rebuilding")

    reach = timeline_end_days(today)
    if settings["lookahead_days"] < reach:
        notes = notes + [f"`lookahead_days` is {settings['lookahead_days']}; using {reach} so the timeline shows "
                         f"{TIMELINE_WEEKS} full weeks."]
        settings["lookahead_days"] = reach
    stale_days = fo.read_stale_days()
    projects = [fo.inspect(e, today, settings["lookahead_days"], stale_days) for e in included]
    # A second, widest read feeds only the page's "Full timeline"; the brief's own windows are untouched.
    wide = [fo.inspect(e, today, MAX_DAYS, stale_days) for e in included]
    note = fo.scope_note(scope, uncategorized)
    time_off, off_notes = read_time_off(Path(args.time_off))
    notes = notes + off_notes
    snoozes = read_snoozes(out / SNOOZES, today)
    sig_notes = signature_notes(projects)
    names = {n.lower() for n in covered(included)}
    applied = [a for a in read_applied(out, today, settings["retention_days"]) if a["project"] in names]
    facts = data(projects, today, settings, notes, note, time_off, read_me(), wide, snoozes, applied, sig_notes)
    facts["covered"] = covered(included)
    write(out, today, render(projects, today, settings, notes, note, time_off, snoozes, sig_notes), facts)
    removed = prune(out, today, settings["retention_days"])
    ok = sum(1 for p in projects if p.get("state") == "ok")
    print(f"wrote {out / f'brief-{today}.md'} and brief-latest.md: {len(projects)} project(s), {ok} readable"
          + (f"; pruned {len(removed)} older brief(s)" if removed else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
